    <h1>Kebijakan Privasi — Study Center Nias (Aplikasi Student)</h1>
    <p><strong>Terakhir diperbarui: 24 Agustus 2026</strong></p>

    <p>Kebijakan Privasi ini menjelaskan bagaimana aplikasi <strong>Study Center Nias Student</strong>
    ("Aplikasi") mengumpulkan, menggunakan, menyimpan, dan melindungi data pribadi pengguna
    ("Anda", siswa peserta program Study Center Nias). Aplikasi ini dikembangkan dan
    dioperasikan oleh <strong>Study Center Nias</strong> untuk mendukung kegiatan akademik dan
    kerohanian siswa binaan.</p>

    <p>Dengan menggunakan Aplikasi ini, Anda menyetujui pengumpulan dan penggunaan data
    sesuai kebijakan ini.</p>

    <h2>1. Data yang Kami Kumpulkan</h2>
    <p>Kami hanya mengumpulkan data yang benar-benar diperlukan untuk fungsi Aplikasi:</p>

    <p><strong>a. Data Akun &amp; Profil</strong></p>
    <ul>
        <li>Nama lengkap, nama pengguna (username), alamat email</li>
        <li>Kata sandi (disimpan terenkripsi di server, tidak pernah dapat dilihat dalam
            bentuk asli oleh siapa pun termasuk pengelola)</li>
        <li>Cabang/wilayah Study Center Anda</li>
        <li>Foto profil (opsional, jika Anda unggah)</li>
        <li>Biografi singkat (opsional, jika Anda isi)</li>
    </ul>

    <p><strong>b. Data Aktivitas Akademik &amp; Kerohanian</strong></p>
    <ul>
        <li>Catatan jurnal harian: status baca Alkitab (Perjanjian Lama/Baru), ayat hafalan
            yang dicatat, kehadiran kelas/pembinaan, dan aktivitas kerohanian/karakter lain
            yang Anda tandai selesai</li>
        <li>Foto bukti belajar yang Anda unggah dari galeri perangkat (opsional, untuk
            melengkapi jurnal harian)</li>
        <li>Laporan/rekap aktivitas dan progres belajar</li>
    </ul>

    <p><strong>c. Data Interaksi Komunitas</strong></p>
    <ul>
        <li>Artikel blog yang Anda buat (jika memiliki akses)</li>
        <li>Komentar yang Anda tulis pada artikel blog</li>
    </ul>

    <p><strong>d. Data Teknis</strong></p>
    <ul>
        <li>Token autentikasi (disimpan terenkripsi di perangkat Anda menggunakan Android
            Keystore, melalui secure storage) — dipakai agar Anda tidak perlu login
            berulang kali</li>
        <li>Kami <strong>tidak</strong> mengumpulkan data lokasi GPS, kontak, riwayat
            panggilan, SMS, atau data sensor perangkat lain</li>
        <li>Kami <strong>tidak</strong> menggunakan layanan analitik pihak ketiga atau iklan
            di dalam Aplikasi</li>
    </ul>

    <h2>2. Izin Perangkat (Android Permissions)</h2>
    <p>Aplikasi meminta izin berikut, hanya digunakan untuk tujuan yang disebutkan:</p>
    <table>
        <tr><th>Izin</th><th>Tujuan</th></tr>
        <tr>
            <td>Internet</td>
            <td>Menghubungkan Aplikasi ke server Study Center Nias untuk sinkronisasi data</td>
        </tr>
        <tr>
            <td>Akses galeri/media (foto)</td>
            <td>Memilih foto dari galeri Anda untuk diunggah sebagai bukti belajar pada
                jurnal harian. Aplikasi <strong>tidak</strong> mengakses kamera secara
                langsung — Anda memilih foto yang sudah ada di galeri</td>
        </tr>
    </table>
    <p>Aplikasi tidak meminta izin lokasi, kontak, mikrofon, kamera langsung, SMS, atau
    penyimpanan penuh perangkat.</p>

    <h2>3. Bagaimana Kami Menggunakan Data Anda</h2>
    <p>Data yang dikumpulkan digunakan semata-mata untuk:</p>
    <ul>
        <li>Menyediakan dan mengoperasikan fitur Aplikasi (jurnal, laporan, blog, profil)</li>
        <li>Memverifikasi identitas Anda saat login</li>
        <li>Menampilkan progres belajar dan laporan aktivitas kepada Anda dan mentor yang
            berwenang di cabang Anda</li>
        <li>Komunikasi terkait program (jika diperlukan oleh pengelola cabang)</li>
    </ul>
    <p>Kami <strong>tidak</strong> menjual, menyewakan, atau membagikan data pribadi Anda
    kepada pihak ketiga untuk tujuan pemasaran.</p>

    <h2>4. Penyimpanan &amp; Keamanan Data</h2>
    <ul>
        <li>Semua data akademik dan profil disimpan di server milik Study Center Nias
            dengan koneksi terenkripsi (HTTPS/TLS) antara Aplikasi dan server</li>
        <li>Kata sandi disimpan menggunakan metode hashing standar industri, bukan teks
            biasa</li>
        <li>Token sesi login disimpan terenkripsi di perangkat Anda dan dapat dihapus
            kapan saja dengan logout dari Aplikasi</li>
        <li>Akses ke data siswa di sisi server dibatasi berdasarkan peran (role) —
            mentor/admin cabang hanya dapat melihat data siswa di cabang mereka</li>
    </ul>

    <h2>5. Berbagi Data dengan Pihak Lain</h2>
    <p>Kami hanya membagikan data dengan:</p>
    <ul>
        <li><strong>Mentor dan pengelola cabang Anda</strong> — untuk keperluan pembinaan
            dan pemantauan progres belajar, sesuai peran masing-masing dalam sistem</li>
        <li><strong>Penyedia layanan infrastruktur</strong> (hosting server) — semata untuk
            menjalankan Aplikasi, bukan untuk tujuan komersial pihak tersebut</li>
    </ul>
    <p>Kami tidak membagikan data Anda ke pengiklan, broker data, atau pihak ketiga lain
    di luar yang disebutkan di atas.</p>

    <h2>6. Hak Anda</h2>
    <ul>
        <li>Melihat dan memperbarui data profil Anda kapan saja melalui menu Profil di
            Aplikasi</li>
        <li>Meminta penghapusan akun dan data terkait dengan menghubungi pengelola cabang
            atau admin Study Center Nias (lihat kontak di bawah)</li>
        <li>Menghapus foto yang telah diunggah kapan saja melalui fitur jurnal</li>
    </ul>

    <h2>7. Data Anak</h2>
    <p>Sebagian pengguna Aplikasi ini adalah siswa di bawah 18 tahun. Kami membatasi
    pengumpulan data hanya pada yang esensial untuk tujuan pendidikan dan pembinaan, dan
    tidak menggunakan data tersebut untuk iklan atau profiling komersial. Orang tua/wali
    yang memiliki pertanyaan tentang data anak dapat menghubungi kami melalui kontak di
    bawah.</p>

    <h2>8. Perubahan Kebijakan Privasi</h2>
    <p>Kebijakan ini dapat diperbarui dari waktu ke waktu. Perubahan signifikan akan
    diinformasikan melalui Aplikasi atau saluran komunikasi resmi Study Center Nias.
    Tanggal "Terakhir diperbarui" di atas mencerminkan revisi terbaru.</p>

    <h2>9. Kontak</h2>
    <p>Jika Anda memiliki pertanyaan mengenai Kebijakan Privasi ini atau ingin mengajukan
    permintaan terkait data Anda, silakan hubungi pengelola cabang Study Center Nias Anda,
    atau melalui website resmi kami.</p>

